import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {stripTypeScriptTypes} from 'node:module';
import {pathToFileURL} from 'node:url';
const [source,output]=process.argv.slice(2);
const manifest=JSON.parse(fs.readFileSync(path.join(source,'SOURCE.json')));
const pin='83a3674ffd84ffb33de768210c806cb1ac53fd80';
if(manifest.revision!==pin||process.versions.node!=='26.13.0')throw Error('Pinned source and Node26.13.0 required');
function read(file){const data=fs.readFileSync(path.join(source,file));if(crypto.createHash('sha256').update(data).digest('hex')!==manifest.files[file])throw Error('Changed source '+file);return data.toString();}
const audio=read('apps/server/src/speech/audio.ts');
const native=read('apps/server/src/speech/native.ts');
const license=read('LICENSE');
const pkg=JSON.parse(read('apps/server/package.json'));
if(pkg.dependencies['transcribe-cpp']!=='0.4.1')throw Error('Unexpected native engine dependency');
const audioJs=stripTypeScriptTypes(audio,{mode:'strip'}).replace('export function createSpeechAudio','function createSpeechAudio');
const nativeJs=stripTypeScriptTypes(native,{mode:'strip'});
const needle='import { createSpeechAudio } from "./audio.ts";';
if(nativeJs.split(needle).length!==2)throw Error('Whole native audio import required');
const bundled=nativeJs.replace(needle,audioJs);
if(/^\s*import\s.*@t3tools/m.test(bundled))throw Error('Unexpected runtime dependency');
const notice='/*\n'+license+'\nSource: T3 Code nightly4314 '+pin+'\nGenerated by erasing types and embedding the complete audio factory.\n*/\n';
const bytes=notice+bundled;
fs.writeFileSync(path.join(output,'native-worker.mjs'),bytes);
fs.writeFileSync(path.join(output,'LICENSE'),license);
const loaded=await import(pathToFileURL(path.join(output,'native-worker.mjs')).href);
const original=await import(pathToFileURL(path.join(source,'apps/server/src/speech/native.ts')).href);
const functionDigests={};
for(const name of ['runNativeSpeechWorker','loadNativeSpeechModel','listNativeSpeechGpuDevices']){
 if(typeof loaded[name]!=='function'||loaded[name].toString()!==original[name].toString())throw Error('Changed whole native function '+name);
 functionDigests[name]=crypto.createHash('sha256').update(original[name].toString()).digest('hex');
}
const result={formatVersion:1,node:'26.13.0',reference:{nightly:4314,revision:pin},engine:{package:'transcribe-cpp',version:'0.4.1'},functionDigests,sources:manifest.files,files:{'native-worker.mjs':{sha256:crypto.createHash('sha256').update(bytes).digest('hex'),bytes:Buffer.byteLength(bytes)},LICENSE:{sha256:crypto.createHash('sha256').update(license).digest('hex'),bytes:Buffer.byteLength(license)}}};
fs.writeFileSync(path.join(output,'native-manifest.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result.files));
